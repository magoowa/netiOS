'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {execFileSync} = require('node:child_process');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const strings = require('../app/strings.json');
const version = require('../package.json').version;
for (const file of ['app/appinfo.json', 'service/package.json', 'package-lock.json']) assert.equal(require(path.join(root,file)).version,version,'Version mismatch: '+file);
for (const value of Object.values(strings)) assert.equal(typeof value, 'string', 'UI text must be a string');
assert(fs.readFileSync(path.join(root,'app/assets/profile-qr.svg'),'utf8').includes('data-url="'+strings['profiles.url']+'"'),'Regenerate profile QR after changing profiles.url');
execFileSync(process.execPath, [path.join(__dirname,'render-branding.cjs')], {stdio:'inherit'});
const stage = path.join(root, 'dist', 'staging');
const app = path.join(stage, 'app');
const service = path.join(stage, 'service');
assert(stage.startsWith(root + path.sep + 'dist' + path.sep));
fs.rmSync(stage, {recursive: true, force: true});
fs.mkdirSync(app, {recursive: true}); fs.mkdirSync(service, {recursive: true});
for (const file of ['appinfo.json', 'index.html', 'main.js', 'image-cache.js', 'quality.js', 'tv-model.js', 'icons.js', 'mdi-component.js', 'frame-login.js', 'webOSTV.js', 'style.css', 'texts.js']) fs.copyFileSync(path.join(root, 'app', file), path.join(app, file));
fs.copyFileSync(path.join(root,'service/config-model.js'),path.join(app,'config-model.js'));
fs.writeFileSync(path.join(app,'strings.js'),'window.NETIOS_STRINGS='+JSON.stringify(strings)+';\n');
for (const file of ['package.json', 'services.json', 'service.js', 'provider.js', 'vault.js', 'account.js', 'user-config.js', 'config-model.js', 'compat.js']) fs.copyFileSync(path.join(root, 'service', file), path.join(service, file));
fs.mkdirSync(path.join(app, 'vendor'), {recursive: true});
fs.copyFileSync(require.resolve('shaka-player/dist/shaka-player.compiled.js'), path.join(app, 'vendor', 'shaka-player.compiled.js'));
fs.copyFileSync(path.join(root, 'node_modules', 'shaka-player', 'LICENSE'), path.join(app, 'vendor', 'SHAKA-LICENSE'));
fs.mkdirSync(path.join(app, 'assets'), {recursive: true});
for (const name of ['netios.svg', 'icon.png', 'splash.png', 'profile-qr.svg']) fs.copyFileSync(path.join(root, 'app', 'assets', name), path.join(app, 'assets', name));
for (const directory of ['fonts', 'licenses']) {
    fs.mkdirSync(path.join(app, 'assets', directory), {recursive: true});
    const names = directory === 'licenses' ? ['MDI-LICENSE', 'JOSEFIN-LICENSE', 'WEBOSTV-LICENSE'] : [400, 600, 700].flatMap(weight => ['latin', 'latin-ext'].map(subset => `josefin-sans-${subset}-${weight}-normal.woff2`));
    for (const name of names) fs.copyFileSync(path.join(root, 'app', 'assets', directory, name), path.join(app, 'assets', directory, name));
}
const png = fs.readFileSync(path.join(app, 'assets', 'icon.png'));
assert.equal(png.subarray(0, 8).toString('hex'), '89504e470d0a1a0a');
fs.copyFileSync(path.join(app, 'assets', 'icon.png'), path.join(app, 'icon.png'));
fs.writeFileSync(path.join(app,'version.js'), 'window.APP_VERSION='+JSON.stringify(require('../package.json').version)+';\n');
const meta = JSON.parse(fs.readFileSync(path.join(app, 'appinfo.json')));
assert.equal(JSON.parse(fs.readFileSync(path.join(service, 'services.json'))).id, meta.id + '.service');
execFileSync(process.execPath, [require.resolve('@webos-tools/cli/bin/ares-package.js'), app, service, '-o', path.join(root, 'dist')], {stdio: 'inherit'});
const name = `${meta.id}_${meta.version}_all.ipk`;
const hash = crypto.createHash('sha256').update(fs.readFileSync(path.join(root, 'dist', name))).digest('hex');
fs.writeFileSync(path.join(root, 'dist', meta.id + '.manifest.json'), JSON.stringify({id: meta.id, version: meta.version, type: 'web', title: meta.title, appDescription: 'netiOS — nieoficjalny klient Netia GO: profile, kanały w pakiecie i odtwarzanie Widevine. Najwyższa jakość na start. Wymaga subskrypcji.', iconUri: 'icon.png', rootRequired: false, ipkUrl: name, ipkHash: {sha256: hash}}, null, 2) + '\n');
fs.copyFileSync(path.join(app, 'icon.png'), path.join(root, 'dist', 'icon.png'));
fs.writeFileSync(path.join(root, 'dist', 'SHA256SUMS'), hash + '  ' + name + '\n');
console.log('Built IPK and Homebrew manifest. Publish only the reviewed release files in dist, never the working folder.');
